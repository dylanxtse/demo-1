const fs = require('node:fs');
const path = require('node:path');

const packageRoot = __dirname;
const sourceRoot = path.join(packageRoot, 'src');
const distRoot = path.join(packageRoot, 'dist');
const readPackage = (relativePath) => fs.readFileSync(path.join(packageRoot, relativePath), 'utf8');
const readSource = (relativePath) => fs.readFileSync(path.join(sourceRoot, relativePath), 'utf8');
const packageManifest = JSON.parse(readPackage('package.json'));
const packageVersion = packageManifest.version || '0.2.1';

const jsSources = [
  { file: 'prototype-tools-theme.js', read: readSource },
  { file: 'annotation-overlay.js', read: readSource },
  { file: 'project-iteration-panel.js', read: readSource },
  { file: 'storage.js', read: readPackage },
  { file: 'theme.js', read: readPackage },
  { file: 'annotation.js', read: readPackage },
  { file: 'iteration.js', read: readPackage },
  { file: 'index.js', read: readPackage }
];

const annotationCssSource = readSource('components.css');
const annotationStart = annotationCssSource.indexOf('/* ===== 统一页面标注覆盖层 =====');
const annotationEnd = annotationCssSource.indexOf('\n.btn-sm {', annotationStart);
if (annotationStart < 0 || annotationEnd < 0) {
  throw new Error('无法定位标注样式边界，请检查 components.css');
}

fs.mkdirSync(distRoot, { recursive: true });
const jsBundle = [
  `/*! Prototype Tools bundle v${packageVersion} | generated by build.cjs */`,
  ...jsSources.map(({ file, read }) => `\n/* --- src/${file} --- */\n${read(file)}`)
].join('\n');
fs.writeFileSync(path.join(distRoot, 'prototype-tools.js'), `${jsBundle.trim()}\n`);

const cssBundle = [
  `/* Prototype Tools bundle v${packageVersion} | generated by build.cjs */`,
  annotationCssSource.slice(annotationStart, annotationEnd),
  readSource('project-iteration-panel.css')
].join('\n\n');
fs.writeFileSync(path.join(distRoot, 'prototype-tools.css'), `${cssBundle.trim()}\n`);

console.log(`Built ${path.relative(process.cwd(), path.join(distRoot, 'prototype-tools.js'))}`);
console.log(`Built ${path.relative(process.cwd(), path.join(distRoot, 'prototype-tools.css'))}`);
